# Builds js/airports.js from the OurAirports data set (public domain, https://ourairports.com/data/).
# Runs in the GitHub pipeline (pwsh on Linux) and locally on Windows:
#   powershell -ExecutionPolicy Bypass -File tools/build-airports.ps1              # downloads the CSV
#   powershell -ExecutionPolicy Bypass -File tools/build-airports.ps1 -Csv a.csv   # uses a local copy
param([string]$Csv)

if (-not $Csv) {
  $Csv = Join-Path ([IO.Path]::GetTempPath()) 'ourairports-airports.csv'
  Invoke-WebRequest -UseBasicParsing -Uri 'https://davidmegginson.github.io/ourairports-data/airports.csv' -OutFile $Csv
}

$out = Join-Path (Join-Path (Split-Path $PSScriptRoot -Parent) 'js') 'airports.js'
$rank = @{ 'large_airport' = 0; 'medium_airport' = 1; 'small_airport' = 2; 'seaplane_base' = 3 }
$inv = [Globalization.CultureInfo]::InvariantCulture

$rows = Import-Csv -Path $Csv | Where-Object {
  $_.iata_code -match '^[A-Z]{3}$' -and $rank.ContainsKey($_.type) -and
  ($_.type -ne 'small_airport' -and $_.type -ne 'seaplane_base' -or $_.scheduled_service -eq 'yes')
} | Sort-Object { $rank[$_.type] }

$seen = @{}
$lines = foreach ($r in $rows) {
  if ($seen.ContainsKey($r.iata_code)) { continue }
  $seen[$r.iata_code] = $true
  $lat = [Math]::Round([double]::Parse($r.latitude_deg, $inv), 3).ToString($inv)
  $lon = [Math]::Round([double]::Parse($r.longitude_deg, $inv), 3).ToString($inv)
  $city = ($r.municipality -replace '[|\r\n\\]', ' ').Trim()
  "$($r.iata_code)|$($r.iso_country)|$lat|$lon|$city"
}

$body = ($lines | Sort-Object) -join "\n"
$js = "/* Airports with an IATA code (IATA|country|lat|lon|city), generated by tools/build-airports.ps1`n" +
      " * from OurAirports (https://ourairports.com/data/, public domain). Used for manually entered routes. */`n" +
      "MM.AIRPORT_DATA = '" + ($body -replace "'", "\'") + "';`n"
[IO.File]::WriteAllText([IO.Path]::GetFullPath($out), $js, (New-Object Text.UTF8Encoding($false)))
Write-Output "Wrote $($seen.Count) airports to $out"
